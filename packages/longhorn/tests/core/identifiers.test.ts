import { describe, expect, test } from "bun:test";

import { isOpaqueId, OPAQUE_ID_RULE } from "@inflatable-cookie/longhorn/core";
import { assertValidOperationMutationCommand } from "@inflatable-cookie/longhorn/operation";
import operation from "../../../../fixtures/operation/protocol-v1.json";

describe("generated opaque-id rule", () => {
  test("admits the characters Rust admits, in any position", () => {
    for (let code = 0; code < 256; code += 1) {
      const character = String.fromCharCode(code);
      expect([character, isOpaqueId(character)]).toEqual([
        character,
        /^[a-z0-9._:-]$/.test(character),
      ]);
    }
  });

  test("bounds the identifier by the generated byte count", () => {
    expect(OPAQUE_ID_RULE.maximumBytes).toBe(128);
    expect(isOpaqueId("a".repeat(128))).toBeTrue();
    expect(isOpaqueId("a".repeat(129))).toBeFalse();
    expect(isOpaqueId("")).toBeFalse();
    expect(isOpaqueId("é")).toBeFalse();
    expect(isOpaqueId(3)).toBeFalse();
  });

  test("applies to operation identifiers, which were only checked for presence", () => {
    const command = operation.mutationCommands.find((entry) => entry.kind === "register");
    expect(() => assertValidOperationMutationCommand(command)).not.toThrow();
    for (const key of ["requestId", "operationId", "kindId", "scopeId", "retryOf"]) {
      expect(() => assertValidOperationMutationCommand({ ...command, [key]: "Not/An:Id" })).toThrow(
        `$.${key}`,
      );
    }
    expect(() =>
      assertValidOperationMutationCommand({
        ...command,
        authority: { ...command!.authority, authorityId: "a".repeat(129) },
      }),
    ).toThrow("$.authority.authorityId");
  });
});
