use std::error::Error;

use longhorn_core::{MAX_OPAQUE_ID_BYTES, OPAQUE_ID_CHARACTERS};

use crate::generation::{Artifact, GENERATE_TASK};

const GENERATED: &str = "packages/longhorn/src/core/generated/identifiers.ts";

/// Renders the identifier rules every TypeScript domain validator shares.
///
/// The rules are emitted here and nowhere else, so a domain cannot carry its
/// own copy that drifts from Rust.
///
/// # Errors
///
/// Returns an error if a rule cannot be serialized.
pub fn render() -> Result<Vec<Artifact>, Box<dyn Error>> {
    let opaque_id_rule = serde_json::json!({
        "maximumBytes": MAX_OPAQUE_ID_BYTES,
        "characters": OPAQUE_ID_CHARACTERS,
    });
    Ok(vec![Artifact {
        relative_path: GENERATED,
        contents: format!(
            "// @generated by `effigy {GENERATE_TASK}`; do not edit.\n\
             // Rust is the identifier authority.\n\n\
             export const OPAQUE_ID_RULE = {opaque_id_rule} as const;\n"
        ),
    }])
}
