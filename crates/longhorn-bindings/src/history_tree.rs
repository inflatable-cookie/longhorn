mod fixture;

// Compile the adapter's wire declarations without linking the Tauri runtime.
#[allow(dead_code)]
#[path = "../../longhorn-tauri-history-tree/src/error.rs"]
mod host_error;

const ARTIFACTS: DomainArtifacts = DomainArtifacts {
    protocol: "packages/longhorn/src/history-tree/generated/protocol.ts",
    fields: "packages/longhorn/src/history-tree/generated/fields.ts",
    fields_constant: "HISTORY_TREE_FIELDS",
    variant_fields: "packages/longhorn/src/history-tree/generated/variant-fields.ts",
    variant_fields_constant: "HISTORY_TREE_VARIANT_FIELDS",
    fixture: "fixtures/history-tree/protocol-v2.json",
};

/// Renders the fork-history bindings and golden fixtures.
///
/// # Errors
///
/// Returns an error if declaration inspection or fixture serialization fails.
pub fn render() -> Result<Vec<Artifact>, Box<dyn Error>> {
    let path_target = ForkPathTargetProjection::decl(config());
    let path_floor = ForkPathFloorProjection::decl(config());
    let navigation_target = ForkNavigationTargetProjection::decl(config());
    let navigation_result = ForkNavigationResult::decl(config());
    let delete_result = ForkDeleteResult::decl(config());
    let retention_code = ForkRetentionRejectionCode::decl(config());
    let prune_result = ForkPruneResult::decl(config());
    let [host_error_code, host_error] =
        crate::serde_shape::error_declarations::<_, host_error::ForkHistoryHostErrorCode>(
            host_error::ForkHistoryHostError::state_unavailable(),
            "ForkHistoryHostError",
            "ForkHistoryHostErrorCode",
        )?;

    let declarations = [
        HistoryId::decl(config()),
        HistoryEntryId::decl(config()),
        HistoryGroupId::decl(config()),
        HistoryKindId::decl(config()),
        HistoryPlanId::decl(config()),
        HistoryRevision::decl(config()),
        HistoryAuthorityEpoch::decl(config()),
        ForkBranchId::decl(config()),
        ForkCheckpointId::decl(config()),
        ForkHistoryProtocolVersion::decl(config()),
        ForkProjectionPosition::decl(config()),
        ForkSummaryProjection::decl(config()),
        ForkSnapshot::decl(config()),
        HistoryRecordedAt::decl(config()),
        ForkEntryRecord::decl(config()),
        path_floor.clone(),
        path_target.clone(),
        ForkPathPageCommand::decl(config()),
        ForkPathPageSnapshot::decl(config()),
        ForkBranchRecord::decl(config()),
        ForkBranchPageCommand::decl(config()),
        ForkBranchPageSnapshot::decl(config()),
        ForkContinuationRecord::decl(config()),
        ForkContinuationPageCommand::decl(config()),
        ForkContinuationPageSnapshot::decl(config()),
        ForkDeleteContinuationCommand::decl(config()),
        retention_code.clone(),
        ForkRetentionRejectionProjection::decl(config()),
        delete_result.clone(),
        ForkRemovedEntryRecord::decl(config()),
        ForkRemovalReceiptProjection::decl(config()),
        ForkPruneCommand::decl(config()),
        prune_result.clone(),
        navigation_target.clone(),
        ForkNavigationCommand::decl(config()),
        ForkNavigationReceiptProjection::decl(config()),
        ForkNavigationRejectionCode::decl(config()),
        ForkNavigationRejectionProjection::decl(config()),
        navigation_result.clone(),
        ForkChangedKind::decl(config()),
        ForkChangedEvent::decl(config()),
        host_error_code,
        host_error,
    ]
    .map(exported_declaration);

    let contents = format!(
        "// @generated by `effigy {GENERATE_TASK}`; do not edit.\n\
         // Rust serde types are authoritative. Product payloads are intentionally absent.\n\n\
         export const FORK_HISTORY_PROTOCOL_VERSION = {FORK_HISTORY_PROTOCOL_VERSION} as const;\n\
         export const MAXIMUM_FORK_HISTORY_PAGE_SIZE = {MAXIMUM_FORK_PROJECTION_PAGE_SIZE} as const;\n\
         export const FORK_HISTORY_ENTRY_POSITIONS = {} as const;\n\
         export const FORK_HISTORY_PATH_TARGETS = {} as const;\n\
         export const FORK_HISTORY_PATH_FLOORS = {} as const;\n\
         export const FORK_HISTORY_NAVIGATION_TARGETS = {} as const;\n\
         export const FORK_HISTORY_NAVIGATION_REJECTION_CODES = {} as const;\n\
         export const FORK_HISTORY_NAVIGATION_STATUSES = {} as const;\n\
         export const FORK_HISTORY_CHANGED_KINDS = {} as const;\n\
         export const FORK_HISTORY_RETENTION_REJECTION_CODES = {} as const;\n\
         export const FORK_HISTORY_DELETE_STATUSES = {} as const;\n\
         export const FORK_HISTORY_PRUNE_STATUSES = {} as const;\n\n\
         {}\n",
        enum_names_json::<ForkProjectionPosition>()?,
        tagged_variants_json(&path_target)?,
        tagged_variants_json(&path_floor)?,
        tagged_variants_json(&navigation_target)?,
        enum_names_json::<ForkNavigationRejectionCode>()?,
        tagged_variants_json(&navigation_result)?,
        enum_names_json::<ForkChangedKind>()?,
        enum_names_json::<ForkRetentionRejectionCode>()?,
        tagged_variants_json(&delete_result)?,
        tagged_variants_json(&prune_result)?,
        declarations.join("\n\n"),
    );

    let mut artifacts = build_domain_artifacts(&ARTIFACTS, contents, &declarations, fixture::render()?)?;
    artifacts.push(crate::serde_shape::error_fixture(
        "fixtures/history-tree/host-errors.json",
        &[
            host_error::ForkHistoryHostError::authority("Host temporarily unavailable", true),
            host_error::ForkHistoryHostError::state_unavailable(),
        ],
    )?);
    Ok(artifacts)
}
