use std::error::Error;

use longhorn_licence::{
    HeldLicenceProjection, LICENCE_PROTOCOL_VERSION, LicenceActivateCommand, LicenceChangedEvent,
    LicenceChangedKind, LicenceCredentialProjection, LicenceDeactivateCommand,
    LicenceEntitlementProjection, LicenceOutcomeProjection, LicenceProtocolVersion,
    LicenceRefreshCommand, LicenceRejectionCode, LicenceReleaseSeatCommand,
    LicenceRenameSeatCommand, LicenceSeatProjection, LicenceSnapshot, LicenceTrustBasisProjection,
    LicenceUsabilityProjection, Timestamp,
};
use ts_rs::TS;

use crate::{
    generation::{
        Artifact, DomainArtifacts, GENERATE_TASK, build_domain_artifacts, config,
        exported_declaration, tagged_variants_json,
    },
    serde_shape::enum_names_json,
};

mod fixture;

// Compile the adapter's wire declarations without linking the Tauri runtime.
#[allow(dead_code)]
#[path = "../../longhorn-tauri-licence/src/error.rs"]
mod host_error;

const ARTIFACTS: DomainArtifacts = DomainArtifacts {
    protocol: "packages/longhorn/src/licence/generated/protocol.ts",
    fields: "packages/longhorn/src/licence/generated/fields.ts",
    fields_constant: "LICENCE_FIELDS",
    variant_fields: "packages/longhorn/src/licence/generated/variant-fields.ts",
    variant_fields_constant: "LICENCE_VARIANT_FIELDS",
    fixture: "fixtures/licence/protocol-v1.json",
};
/// Cases the TypeScript key parser must agree with the Rust one on.
///
/// Generated rather than hand-kept: two implementations of one format drift,
/// and the only defence is a fixture neither side authors.
const GENERATED_KEY_CONFORMANCE: &str =
    "packages/longhorn/src/licence/generated/key-conformance.json";

/// Renders the licence bindings and golden fixtures.
///
/// # Errors
///
/// Returns an error if declaration inspection or fixture serialization fails.
pub fn render() -> Result<Vec<Artifact>, Box<dyn Error>> {
    let usability = LicenceUsabilityProjection::decl(config());
    let trust_basis = LicenceTrustBasisProjection::decl(config());
    let credential = LicenceCredentialProjection::decl(config());
    let outcome = LicenceOutcomeProjection::decl(config());

    let [host_error_code, host_error] =
        crate::serde_shape::error_declarations::<_, host_error::LicenceHostErrorCode>(
            host_error::LicenceHostError::state_unavailable(),
            "LicenceHostError",
            "LicenceHostErrorCode",
        )?;

    let declarations = [
        LicenceProtocolVersion::decl(config()),
        Timestamp::decl(config()),
        usability.clone(),
        trust_basis.clone(),
        LicenceEntitlementProjection::decl(config()),
        LicenceSeatProjection::decl(config()),
        HeldLicenceProjection::decl(config()),
        LicenceSnapshot::decl(config()),
        credential.clone(),
        LicenceActivateCommand::decl(config()),
        LicenceDeactivateCommand::decl(config()),
        LicenceRefreshCommand::decl(config()),
        LicenceReleaseSeatCommand::decl(config()),
        LicenceRenameSeatCommand::decl(config()),
        LicenceRejectionCode::decl(config()),
        outcome.clone(),
        LicenceChangedKind::decl(config()),
        LicenceChangedEvent::decl(config()),
        host_error_code,
        host_error,
    ]
    .map(exported_declaration);

    let contents = format!(
        "// @generated by `effigy {GENERATE_TASK}`; do not edit.\n\
         // Rust serde types are the wire authority. Entitlements are opaque\n\
         // ids: Longhorn answers \"entitled?\" and enumerates no features.\n\n\
         export const LICENCE_PROTOCOL_VERSION = {LICENCE_PROTOCOL_VERSION} as const;\n\
         export const LICENCE_USABILITY_STATES = {} as const;\n\
         export const LICENCE_TRUST_BASIS_KINDS = {} as const;\n\
         export const LICENCE_CREDENTIAL_KINDS = {} as const;\n\
         export const LICENCE_REJECTION_CODES = {} as const;\n\
         export const LICENCE_OUTCOME_STATUSES = {} as const;\n\
         export const LICENCE_CHANGED_KINDS = {} as const;\n\n\
         {}\n",
        tagged_variants_json(&usability)?,
        tagged_variants_json(&trust_basis)?,
        tagged_variants_json(&credential)?,
        enum_names_json::<LicenceRejectionCode>()?,
        tagged_variants_json(&outcome)?,
        enum_names_json::<LicenceChangedKind>()?,
        declarations.join("\n\n"),
    );

    let cases: Vec<_> = longhorn_licence::key_conformance_cases()
        .into_iter()
        .map(|(input, outcome)| serde_json::json!({ "input": input, "outcome": outcome }))
        .collect();
    let key_conformance = format!("{}\n", serde_json::to_string_pretty(&cases)?);

    let mut artifacts =
        build_domain_artifacts(&ARTIFACTS, contents, &declarations, fixture::render()?)?;
    artifacts.push(Artifact {
        relative_path: GENERATED_KEY_CONFORMANCE,
        contents: key_conformance,
    });
    artifacts.push(crate::serde_shape::error_fixture(
        "fixtures/licence/host-errors.json",
        &[
            host_error::LicenceHostError::authority("Host temporarily unavailable", true),
            host_error::LicenceHostError::state_unavailable(),
        ],
    )?);
    Ok(artifacts)
}
