use std::error::Error;

use longhorn_core::DisplayId;
use longhorn_surface_transfer::{
    SurfaceProvisioningCompletion, SurfaceSessionResponse, SurfaceSessionStartRequest,
    SurfaceTransferAbort, SurfaceTransferAbortSource, SurfaceTransferCommand,
    SurfaceTransferCompletion, SurfaceTransferErrorCode, SurfaceTransferResponse,
    SurfaceTransferTarget,
};
use ts_rs::TS;

use crate::{
    generation::{
        Artifact, DomainArtifacts, GENERATE_TASK, build_domain_artifacts, config,
        exported_declaration, tagged_variants_json,
    },
    serde_shape::enum_names,
};

mod fixture;

const ARTIFACTS: DomainArtifacts = DomainArtifacts {
    protocol: "packages/longhorn/src/surface-transfer/generated/protocol.ts",
    fields: "packages/longhorn/src/surface-transfer/generated/fields.ts",
    fields_constant: "SURFACE_TRANSFER_FIELDS",
    variant_fields: "packages/longhorn/src/surface-transfer/generated/variant-fields.ts",
    variant_fields_constant: "SURFACE_TRANSFER_VARIANT_FIELDS",
    fixture: "fixtures/surface-transfer/protocol-v1.json",
};

/// Renders the surface-transfer bindings and golden fixtures.
///
/// # Errors
///
/// Returns an error if declaration inspection or fixture serialization fails.
pub fn render() -> Result<Vec<Artifact>, Box<dyn Error>> {
    let target = SurfaceTransferTarget::decl(config());
    let abort_source = SurfaceTransferAbortSource::decl(config());
    let session_response = SurfaceSessionResponse::decl(config());
    let transfer_response = SurfaceTransferResponse::decl(config());
    let error_codes = enum_names::<SurfaceTransferErrorCode>()?;
    let declarations = [
        DisplayId::decl(config()),
        SurfaceTransferErrorCode::decl(config()),
        SurfaceSessionStartRequest::decl(config()),
        SurfaceTransferCommand::decl(config()),
        SurfaceProvisioningCompletion::decl(config()),
        target.clone(),
        SurfaceTransferCompletion::decl(config()),
        abort_source.clone(),
        SurfaceTransferAbort::decl(config()),
        session_response.clone(),
        transfer_response.clone(),
    ]
    .map(exported_declaration);

    let contents = format!(
        "// @generated by `effigy {GENERATE_TASK}`; do not edit.\n\
         // Rust serde types are the wire authority.\n\n\
         import type {{ SurfaceDocument, SurfaceId, SurfaceMutationRejectionCode, SurfaceRevision }} from \"@inflatable-cookie/longhorn/surfaces\";\n\
         import type {{ DragSessionId, TransferCommitSelector, TransferCommittedTarget, TransferErrorCode, TransferHostBindingId, TransferProtocolVersion, TransferRequestId, TransferSessionStarted, WindowId }} from \"@inflatable-cookie/longhorn/transfer\";\n\n\
         export const SURFACE_TRANSFER_TARGET_KINDS = {} as const;\n\
         export const SURFACE_TRANSFER_ABORT_DOMAINS = {} as const;\n\
         export const SURFACE_SESSION_RESPONSE_STATUSES = {} as const;\n\
         export const SURFACE_TRANSFER_RESPONSE_STATUSES = {} as const;\n\
         export const SURFACE_TRANSFER_ERROR_CODES = {} as const;\n\n\
         {}\n",
        tagged_variants_json(&target)?,
        tagged_variants_json(&abort_source)?,
        tagged_variants_json(&session_response)?,
        tagged_variants_json(&transfer_response)?,
        serde_json::to_string(error_codes)?,
        declarations.join("\n\n")
    );

    build_domain_artifacts(
        &ARTIFACTS,
        contents,
        &declarations,
        fixture::render(error_codes)?,
    )
}
