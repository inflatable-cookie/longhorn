use std::error::Error;

use longhorn_agent_control::{
    BeginSelectionArgs, BeginSelectionError, ElementRef, FileInputFile, PageEvent, PageEventBatch,
    PageState, SelectionFilter, SelectionId, SelectionKind, SemanticNode, ToolError, WaitPredicate,
    WebviewLabel,
};
use longhorn_core::{CommandId, WindowId};
use serde_json::json;
use ts_rs::TS;

use crate::generation::{Artifact, GENERATE_TASK, config, exported_declaration};

pub(crate) fn render() -> Result<Vec<Artifact>, Box<dyn Error>> {
    let declarations = [
        ElementRef::decl(config()),
        WebviewLabel::decl(config()),
        SelectionId::decl(config()),
        WindowId::decl(config()),
        CommandId::decl(config()),
        SemanticNode::decl(config()),
        PageState::decl(config()),
        PageEvent::decl(config()),
        PageEventBatch::decl(config()),
        WaitPredicate::decl(config()),
        FileInputFile::decl(config()),
        ToolError::decl(config()),
        SelectionKind::decl(config()),
        SelectionFilter::decl(config()),
        BeginSelectionArgs::decl(config()),
    ]
    .map(|declaration| {
        exported_declaration(declaration)
            .lines()
            .map(str::trim_end)
            .collect::<Vec<_>>()
            .join("\n")
    })
    .join("\n\n");

    Ok(vec![
        Artifact {
            relative_path: "packages/longhorn/src/agent-control/generated/protocol.ts",
            contents: format!(
                "// @generated by `effigy {GENERATE_TASK}`; do not edit.\n\n{declarations}\n"
            ),
        },
        Artifact {
            relative_path: "fixtures/agent-control/protocol-v1.json",
            contents: format!("{}\n", serde_json::to_string_pretty(&samples()?)?),
        },
    ])
}

