use std::error::Error;

use longhorn_agent_control::{
    BeginSelectionArgs, BeginSelectionError, SelectionFilter, SelectionKind, ToolError,
};
use serde_json::json;
use ts_rs::TS;

use crate::generation::{Artifact, GENERATE_TASK, config, exported_declaration};

pub(crate) fn render() -> Result<Vec<Artifact>, Box<dyn Error>> {
    let declarations = [
        SelectionKind::decl(config()),
        SelectionFilter::decl(config()),
        BeginSelectionArgs::decl(config()),
    ]
    .map(|declaration| {
        exported_declaration(declaration)
            .lines()
            .map(str::trim_end)
            .collect::<Vec<_>>()
            .join("\n")
    })
    .join("\n\n");

    let request = BeginSelectionArgs {
        kind: SelectionKind::Open,
        directory: true,
        multiple: false,
        filters: vec![SelectionFilter {
            name: "Project".to_owned(),
            extensions: vec!["json".to_owned()],
        }],
        title: Some("Choose folder".to_owned()),
        default_path: Some("/projects".to_owned()),
    };
    let samples = json!({
        "beginSelection": { "options": request },
        "beginFailure": ToolError::from(BeginSelectionError::InvalidSaveOptions),
    });

    Ok(vec![
        Artifact {
            relative_path: "packages/longhorn/src/agent-control/generated/protocol.ts",
            contents: format!(
                "// @generated by `effigy {GENERATE_TASK}`; do not edit.\n\n{declarations}\n"
            ),
        },
        Artifact {
            relative_path: "fixtures/agent-control/protocol-v1.json",
            contents: format!("{}\n", serde_json::to_string_pretty(&samples)?),
        },
    ])
}
