use std::error::Error;

use longhorn_update::{
    Channel, DeferralCause, InstallManager, OfferReason, UPDATE_PROTOCOL_VERSION,
    UpdateApplyCommand, UpdateAvailabilityProjection, UpdateCancelCommand, UpdateChangedEvent,
    UpdateChangedKind, UpdateCheckCommand, UpdateDeferCommand, UpdateDeferralProjection,
    UpdateInstallAuthorizationProjection, UpdateOutcomeProjection, UpdatePrepareCommand,
    UpdateProgressEvent, UpdateProgressProjection, UpdateProtocolVersion, UpdateRejectionCode,
    UpdateSelectChannelCommand, UpdateSnapshot, UpdateStagedArtifactProjection,
};
use ts_rs::TS;

use crate::{
    generation::{
        Artifact, DomainArtifacts, GENERATE_TASK, build_domain_artifacts, config,
        exported_declaration, tagged_variants_json,
    },
    serde_shape::enum_names_json,
};

mod fixture;

// Compile the adapter's wire declarations without linking the Tauri runtime.
#[allow(dead_code)]
#[path = "../../longhorn-tauri-update/src/error.rs"]
mod host_error;

const ARTIFACTS: DomainArtifacts = DomainArtifacts {
    protocol: "packages/longhorn/src/update/generated/protocol.ts",
    fields: "packages/longhorn/src/update/generated/fields.ts",
    fields_constant: "UPDATE_FIELDS",
    variant_fields: "packages/longhorn/src/update/generated/variant-fields.ts",
    variant_fields_constant: "UPDATE_VARIANT_FIELDS",
    fixture: "fixtures/update/protocol-v1.json",
};

/// Renders the update bindings and golden fixtures.
///
/// # Errors
///
/// Returns an error if declaration inspection or fixture serialization fails.
pub fn render() -> Result<Vec<Artifact>, Box<dyn Error>> {
    let deferral_cause = DeferralCause::decl(config());
    let availability = UpdateAvailabilityProjection::decl(config());
    let progress = UpdateProgressProjection::decl(config());
    let authorization = UpdateInstallAuthorizationProjection::decl(config());
    let outcome = UpdateOutcomeProjection::decl(config());

    let [host_error_code, host_error] =
        crate::serde_shape::error_declarations::<_, host_error::UpdateHostErrorCode>(
            host_error::UpdateHostError::state_unavailable(),
            "UpdateHostError",
            "UpdateHostErrorCode",
        )?;

    let declarations = [
        UpdateProtocolVersion::decl(config()),
        Channel::decl(config()),
        OfferReason::decl(config()),
        InstallManager::decl(config()),
        deferral_cause.clone(),
        availability.clone(),
        UpdateDeferralProjection::decl(config()),
        UpdateStagedArtifactProjection::decl(config()),
        progress.clone(),
        UpdateProgressEvent::decl(config()),
        UpdateSnapshot::decl(config()),
        UpdateCheckCommand::decl(config()),
        UpdateSelectChannelCommand::decl(config()),
        UpdateDeferCommand::decl(config()),
        UpdatePrepareCommand::decl(config()),
        UpdateApplyCommand::decl(config()),
        UpdateCancelCommand::decl(config()),
        authorization.clone(),
        UpdateRejectionCode::decl(config()),
        outcome.clone(),
        UpdateChangedKind::decl(config()),
        UpdateChangedEvent::decl(config()),
        host_error_code,
        host_error,
    ]
    .map(exported_declaration);

    let contents = format!(
        "// @generated by `effigy {GENERATE_TASK}`; do not edit.\n\
         // Rust serde types are the wire authority. Versions are strings, as\n\
         // `semver::Version` serialises them.\n\n\
         export const UPDATE_PROTOCOL_VERSION = {UPDATE_PROTOCOL_VERSION} as const;\n\
         export const UPDATE_CHANNELS = {} as const;\n\
         export const UPDATE_OFFER_REASONS = {} as const;\n\
         export const UPDATE_INSTALL_MANAGERS = {} as const;\n\
         export const UPDATE_DEFERRAL_CAUSES = {} as const;\n\
         export const UPDATE_AVAILABILITY_STATES = {} as const;\n\
         export const UPDATE_PROGRESS_STATES = {} as const;\n\
         export const UPDATE_INSTALL_AUTHORIZATION_STATUSES = {} as const;\n\
         export const UPDATE_REJECTION_CODES = {} as const;\n\
         export const UPDATE_OUTCOME_STATUSES = {} as const;\n\
         export const UPDATE_CHANGED_KINDS = {} as const;\n\n\
         {}\n",
        enum_names_json::<Channel>()?,
        enum_names_json::<OfferReason>()?,
        enum_names_json::<InstallManager>()?,
        tagged_variants_json(&deferral_cause)?,
        tagged_variants_json(&availability)?,
        tagged_variants_json(&progress)?,
        tagged_variants_json(&authorization)?,
        enum_names_json::<UpdateRejectionCode>()?,
        tagged_variants_json(&outcome)?,
        enum_names_json::<UpdateChangedKind>()?,
        declarations.join("\n\n"),
    );

    let mut artifacts = build_domain_artifacts(&ARTIFACTS, contents, &declarations, fixture::render()?)?;
    artifacts.push(crate::serde_shape::error_fixture(
        "fixtures/update/host-errors.json",
        &[
            host_error::UpdateHostError::authority("Host temporarily unavailable", true),
            host_error::UpdateHostError::state_unavailable(),
        ],
    )?);
    Ok(artifacts)
}
