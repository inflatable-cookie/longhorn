// Heuristics shared by the retired effigy scanner ports: `check-markers.ts`
// (attention markers) and `check-generated-sources.ts` (generated-in-src).
//
// Ported from effigy's `scan generated-in-src` and `scan attention-markers`,
// as built in the stable release 8a58403 (the repository's last effigy with
// these scanners). Effigy 0.15 removed them. Both ports share one copy of the
// two helpers below, so each fact has one owner.

// Blanks out string literals (single, double and backtick quotes, Rust-style raw
// strings) so markers inside them do not count. Mirrors the scanner's mask: each
// literal character becomes a space, so columns and the rest of the line survive.
export function maskStringLiterals(line: string): string {
  const chars = Array.from(line);
  const out: Array<string> = [];
  let index = 0;
  let quote: string | undefined;
  let rawHashes: number | undefined;
  let escaped = false;
  while (index < chars.length) {
    if (rawHashes !== undefined) {
      const closing = chars.slice(index + 1, index + 1 + rawHashes);
      if (
        chars[index] === '"' &&
        closing.length === rawHashes &&
        closing.every((char) => char === "#")
      ) {
        out.push(" ".repeat(1 + rawHashes));
        index += 1 + rawHashes;
        rawHashes = undefined;
        continue;
      }
      out.push(" ");
      index += 1;
      continue;
    }
    const ch = chars[index] ?? "";
    if (quote !== undefined) {
      if (escaped) {
        escaped = false;
      } else if (ch === "\\") {
        escaped = true;
      } else if (ch === quote) {
        quote = undefined;
      }
      out.push(" ");
      index += 1;
      continue;
    }
    const raw = rawStringPrefix(chars, index);
    if (raw !== undefined) {
      out.push(" ".repeat(raw.consumed));
      index += raw.consumed;
      rawHashes = raw.hashes;
      continue;
    }
    if (ch === "'" || ch === '"' || ch === "`") {
      quote = ch;
      out.push(" ");
    } else {
      out.push(ch);
    }
    index += 1;
  }
  return out.join("");
}

function rawStringPrefix(
  chars: ReadonlyArray<string>,
  index: number,
): { readonly consumed: number; readonly hashes: number } | undefined {
  let cursor = index;
  if (chars[cursor] === "b" && chars[cursor + 1] === "r") {
    cursor += 2;
  } else if (chars[cursor] === "r") {
    cursor += 1;
  } else {
    return undefined;
  }
  let hashes = 0;
  while (chars[cursor] === "#") {
    hashes += 1;
    cursor += 1;
  }
  if (chars[cursor] !== '"') {
    return undefined;
  }
  return { consumed: cursor - index + 1, hashes };
}

// The header phrases the scanner matched (its `GENERATED_MARKERS`).
export const GENERATED_HEADER_PHRASES: ReadonlyArray<string> = [
  "@generated",
  "auto-generated",
  "autogenerated",
  "code generated",
  "do not edit",
  "generated by",
];

const COMMENT_PREFIXES: ReadonlyArray<string> = ["//", "/*", "*", "<!--", "--", ";"];
const HEADER_LINES = 24;

// One line is a generated header when, lowercased and with literals masked, it
// is comment-like and contains a header phrase.
export function isGeneratedHeaderLine(rawLine: string): boolean {
  const lower = maskStringLiterals(rawLine).toLowerCase();
  const trimmed = lower.trimStart();
  const commentLike =
    COMMENT_PREFIXES.some((prefix) => trimmed.startsWith(prefix)) ||
    (trimmed.startsWith("#") && !trimmed.startsWith("#["));
  return commentLike && GENERATED_HEADER_PHRASES.some((phrase) => lower.includes(phrase));
}

// True when one of the first 24 lines is a generated header.
export function hasGeneratedHeader(text: string): boolean {
  return text.split(/\r?\n/).slice(0, HEADER_LINES).some(isGeneratedHeaderLine);
}
