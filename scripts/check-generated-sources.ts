// Generated-source detection: the retired `scan generated-in-src` rules, ported
// to a gate. Effigy 0.15 removed the scanner and its `[scan.generated_in_src]`
// table. The rules below are the scanner's `generated_in_src_reason`, applied
// in its order, over the scanner's source roots:
//   1. A generated header in the first 24 lines of the first 16 KiB, comment-like
//      and with string literals masked (`generated-marker`).
//   2. A name ending in `.map`: a source map (`source-map`).
//   3. A name containing `.min.`: a minified asset (`minified-asset`).
//   4. A name containing a generated-name marker (`filename-marker`). `.map` is
//      unanchored, so `a.mapper.ts` counts, as the scanner counted it.
//   5. A path component named `generated` or `gen` (`generated-path-component`).
// The scanner's severity classes come from byte size: warning from 1 byte, high
// from 20,000, critical from 200,000. The retired table's exclude list is the
// allowed generated surface, skipped before the rules run.
//
// Two rules are this repository's own. Outside the source roots, the generator
// header may appear only on the allowed surface. Every file in the generated
// output must be named by a bindings generator, and every text file there must
// carry the header. JSON cannot carry a comment, so JSON is checked by its path.

import { spawnSync } from "node:child_process";
import { readFile } from "node:fs/promises";
import { resolve } from "node:path";

import { hasGeneratedHeader } from "./scanner-heuristics.ts";

const repoRoot = resolve(import.meta.dir, "..");

// The header the effigy bindings generators write at the top of each output.
export const GENERATOR_HEADER = "@generated by `effigy ";

// The scanner's source roots: `src/**`, `app/**`, `lib/**`, `crates/**`,
// `packages/*/src/**` and `services/*/src/**`.
const SOURCE_ROOTS: ReadonlyArray<RegExp> = [
  /^(?:src|app|lib|crates)\//,
  /^(?:packages|services)\/[^/]+\/src\//,
];

// The retired table's exclude list, kept as the allowed generated surface.
const GENERATED_OUTPUT = /^packages\/[^/]+\/src\/(?:.+\/)?generated\//;
const ALLOWED_GENERATED: ReadonlyArray<RegExp> = [
  GENERATED_OUTPUT,
  /^crates\/[^/]+\/bindings\//,
  /^crates\/longhorn-bindings\/src\//,
];
const GENERATOR_SOURCE = /^crates\/longhorn-bindings\/src\/.+\.rs$/;

// The scanner's constants: name markers and path components.
const GENERATED_NAME_MARKERS: ReadonlyArray<string> = [
  ".bundle.",
  ".chunk.",
  ".generated.",
  ".map",
  ".min.",
];
const GENERATED_PATH_COMPONENTS: ReadonlySet<string> = new Set(["generated", "gen"]);

// The scanner's byte window and severity classes (its defaults; the retired
// table set no thresholds).
export const SAMPLE_BYTES = 16 * 1024;
export const THRESHOLDS = { warn: 1, high: 20_000, critical: 200_000 } as const;

// This check and its test name the header and markers as data, not as output.
const HEADER_DATA_EXCLUDES = [
  ":(exclude)scripts/check-generated-sources.ts",
  ":(exclude)scripts/check-generated-sources.test.ts",
  ":(exclude)scripts/scanner-heuristics.ts",
  ":(exclude)scripts/scanner-heuristics.test.ts",
];

export type GeneratedInSrcReason =
  | "generated-marker"
  | "source-map"
  | "minified-asset"
  | "filename-marker"
  | "generated-path-component";

export type SourceFile = {
  readonly path: string;
  readonly bytes: number;
  // The first 16 KiB of the file, decoded as the scanner decoded it.
  readonly sample: string;
};

export type GeneratedSourceInputs = {
  // Source-root files, and any tracked file that carries the generator header.
  readonly files: ReadonlyArray<SourceFile>;
  // Full text of the bindings generator sources, which name each output path.
  readonly generatorSource: string;
};

export function isSourceRootPath(path: string): boolean {
  return SOURCE_ROOTS.some((root) => root.test(path));
}

export function isAllowedGeneratedPath(path: string): boolean {
  return ALLOWED_GENERATED.some((allowed) => allowed.test(path));
}

// Rules 1 to 5, in the scanner's order. The first match is the reason.
export function generatedInSrcReason(
  path: string,
  sample: string,
): GeneratedInSrcReason | undefined {
  if (hasGeneratedHeader(sample)) {
    return "generated-marker";
  }
  const name = (path.split("/").at(-1) ?? "").toLowerCase();
  if (name.endsWith(".map")) {
    return "source-map";
  }
  if (name.includes(".min.")) {
    return "minified-asset";
  }
  if (
    GENERATED_NAME_MARKERS.some((marker) => name.includes(marker)) ||
    name.endsWith(".generated.rs") ||
    name.includes(".pb.") ||
    name.includes(".designer.") ||
    name.includes(".g.")
  ) {
    return "filename-marker";
  }
  if (path.split("/").some((component) => GENERATED_PATH_COMPONENTS.has(component))) {
    return "generated-path-component";
  }
  return undefined;
}

export function generatedInSrcSeverity(bytes: number): "critical" | "high" | "warning" | undefined {
  if (bytes >= THRESHOLDS.critical) {
    return "critical";
  }
  if (bytes >= THRESHOLDS.high) {
    return "high";
  }
  if (bytes >= THRESHOLDS.warn) {
    return "warning";
  }
  return undefined;
}

// A finding is a reason at a severity. Zero-byte files classify as nothing.
export function generatedInSrcFinding(
  file: SourceFile,
):
  | { readonly reason: GeneratedInSrcReason; readonly severity: "critical" | "high" | "warning" }
  | undefined {
  const severity = generatedInSrcSeverity(file.bytes);
  const reason = generatedInSrcReason(file.path, file.sample);
  if (severity === undefined || reason === undefined) {
    return undefined;
  }
  return { reason, severity };
}

export function generatedSourceProblems(inputs: GeneratedSourceInputs): Array<string> {
  const problems: Array<string> = [];
  for (const file of inputs.files) {
    if (!isAllowedGeneratedPath(file.path)) {
      if (isSourceRootPath(file.path)) {
        const finding = generatedInSrcFinding(file);
        if (finding !== undefined) {
          problems.push(`${file.path}: ${finding.reason} in a source tree`);
        }
      } else if (file.sample.includes(GENERATOR_HEADER)) {
        problems.push(
          `${file.path}: generator header outside generated output and the bindings generator sources`,
        );
      }
    }
    if (GENERATED_OUTPUT.test(file.path)) {
      if (!file.path.endsWith(".json") && !file.sample.includes(GENERATOR_HEADER)) {
        problems.push(`${file.path}: file in a generated directory lacks the generator header`);
      }
      if (!inputs.generatorSource.includes(file.path)) {
        problems.push(
          `${file.path}: file in a generated directory is not named by a bindings generator`,
        );
      }
    }
  }
  return problems;
}

function git(args: ReadonlyArray<string>): string {
  const result = spawnSync("git", [...args], { cwd: repoRoot, encoding: "utf8" });
  // git grep exits 1 when nothing matches; other failures are errors.
  if (result.status === 1) {
    return "";
  }
  if (result.status !== 0) {
    throw new Error(`git ${args[0]} failed: ${result.stderr || String(result.error)}`);
  }
  return result.stdout;
}

export async function gatherGeneratedSourceInputs(): Promise<GeneratedSourceInputs> {
  const tracked = git(["ls-files"])
    .split("\n")
    .filter((path) => path !== "");
  const headerPaths = git([
    "grep",
    "-l",
    "-F",
    "-e",
    GENERATOR_HEADER,
    "--",
    ".",
    ...HEADER_DATA_EXCLUDES,
  ])
    .split("\n")
    .filter((path) => path !== "");
  const wanted = [...new Set([...tracked.filter(isSourceRootPath), ...headerPaths])];
  const files = await Promise.all(
    wanted.map(async (path): Promise<SourceFile> => {
      const buffer = await readFile(resolve(repoRoot, path));
      return {
        path,
        bytes: buffer.length,
        sample: buffer.subarray(0, SAMPLE_BYTES).toString("utf8"),
      };
    }),
  );
  const generatorPaths = tracked.filter((path) => GENERATOR_SOURCE.test(path));
  const generatorTexts = await Promise.all(
    generatorPaths.map((path) => readFile(resolve(repoRoot, path), "utf8")),
  );
  return { files, generatorSource: generatorTexts.join("\n") };
}

if (import.meta.main) {
  const problems = generatedSourceProblems(await gatherGeneratedSourceInputs());
  if (problems.length > 0) {
    for (const problem of problems) {
      console.error(`check:generated-sources: ${problem}`);
    }
    process.exit(1);
  }
  console.log("check:generated-sources: generated output and generator sources agree");
}
