// Generated-source detection, the current form of the retired
// `[scan.generated_in_src]` table.
//
// That table told doctor which generated content in source trees was expected,
// and flagged the generator header anywhere else. Effigy 0.15 no longer scans,
// so this check keeps the rule as a gate. The header the bindings generators
// write may appear only in their output (packages/*/src/**/generated/) and in
// the generator sources that write it (crates/longhorn-bindings/src). Every
// file in a generated directory must be named by a generator, and every text
// file there must carry the header. JSON cannot carry a comment, so JSON is
// checked by its generator path alone.

import { spawnSync } from "node:child_process";
import { readFile } from "node:fs/promises";
import { resolve } from "node:path";

const repoRoot = resolve(import.meta.dir, "..");

// The header the effigy bindings generators write at the top of each output.
export const GENERATOR_HEADER = "@generated by `effigy ";

const GENERATED_DIR = /^packages\/[^/]+\/src\/(?:.+\/)?generated\//;
const GENERATOR_SOURCE = /^crates\/longhorn-bindings\/src\/.+\.rs$/;

// This check and its test name the header as data, not as generated output.
const HEADER_DATA_EXCLUDES = [
  ":(exclude)scripts/check-generated-sources.ts",
  ":(exclude)scripts/check-generated-sources.test.ts",
];

export type GeneratedSourceInputs = {
  // Tracked paths whose text contains the generator header.
  readonly headerPaths: ReadonlyArray<string>;
  // Tracked files under a generated directory, and whether each has the header.
  readonly generatedFiles: ReadonlyArray<{ readonly path: string; readonly hasHeader: boolean }>;
  // Concatenated text of the bindings generator sources, which name each output.
  readonly generatorSource: string;
};

export function generatedSourceProblems(inputs: GeneratedSourceInputs): Array<string> {
  const problems: Array<string> = [];
  for (const path of inputs.headerPaths) {
    if (!GENERATED_DIR.test(path) && !GENERATOR_SOURCE.test(path)) {
      problems.push(
        `${path}: generator header outside generated output and the bindings generator sources`,
      );
    }
  }
  for (const file of inputs.generatedFiles) {
    if (!file.path.endsWith(".json") && !file.hasHeader) {
      problems.push(`${file.path}: file in a generated directory lacks the generator header`);
    }
    if (!inputs.generatorSource.includes(file.path)) {
      problems.push(
        `${file.path}: file in a generated directory is not named by a bindings generator`,
      );
    }
  }
  return problems;
}

function git(args: ReadonlyArray<string>): string {
  const result = spawnSync("git", [...args], { cwd: repoRoot, encoding: "utf8" });
  // git grep exits 1 when nothing matches; other failures are errors.
  if (result.status === 1) {
    return "";
  }
  if (result.status !== 0) {
    throw new Error(`git ${args[0]} failed: ${result.stderr || String(result.error)}`);
  }
  return result.stdout;
}

export async function gatherGeneratedSourceInputs(): Promise<GeneratedSourceInputs> {
  const headerPaths = git([
    "grep",
    "-l",
    "-F",
    "-e",
    GENERATOR_HEADER,
    "--",
    ".",
    ...HEADER_DATA_EXCLUDES,
  ])
    .split("\n")
    .filter((path) => path !== "");
  const tracked = git(["ls-files"]).split("\n");
  const generatedPaths = tracked.filter((path) => GENERATED_DIR.test(path));
  const generatedFiles = await Promise.all(
    generatedPaths.map(async (path) => ({
      path,
      hasHeader: (await readFile(resolve(repoRoot, path), "utf8")).includes(GENERATOR_HEADER),
    })),
  );
  const generatorTexts = await Promise.all(
    tracked
      .filter((path) => GENERATOR_SOURCE.test(path))
      .map((path) => readFile(resolve(repoRoot, path), "utf8")),
  );
  return { headerPaths, generatedFiles, generatorSource: generatorTexts.join("\n") };
}

if (import.meta.main) {
  const problems = generatedSourceProblems(await gatherGeneratedSourceInputs());
  if (problems.length > 0) {
    for (const problem of problems) {
      console.error(`check:generated-sources: ${problem}`);
    }
    process.exit(1);
  }
  console.log("check:generated-sources: generated output and generator sources agree");
}
