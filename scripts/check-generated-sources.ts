// Generated-source detection, the current form of the retired
// `[scan.generated_in_src]` table.
//
// Effigy 0.14.1 ran `scan generated-in-src` over the source roots `src`, `app`,
// `lib`, `crates`, `packages/*/src` and `services/*/src`. It flagged a file as
// generated when any of three rules matched (effigy-scan's
// `is_generated_artifact`): a path component named `gen` or `generated`; a file
// name containing a generated-name marker such as `.generated.` or `.min.`; or a
// generated header marker in a comment-like line among the first 24 lines, after
// string literals are masked so prose inside a string does not count. Effigy
// 0.15 removed that scanner and its table, so this check ports the same three
// rules as a gate. The table's exclude list survives as the allowed generated
// surface: the bindings output and the generator sources that write it.
//
// Outside those source roots the generator header may appear only in the
// allowed surface. Every file in the generated output must be named by a
// bindings generator, and every text file there must carry the header. JSON
// cannot carry a comment, so JSON is checked by its generator path alone.

import { spawnSync } from "node:child_process";
import { readFile } from "node:fs/promises";
import { resolve } from "node:path";

const repoRoot = resolve(import.meta.dir, "..");

// The header the effigy bindings generators write at the top of each output.
export const GENERATOR_HEADER = "@generated by `effigy ";

// The scanner's source roots: `src/**`, `app/**`, `lib/**`, `crates/**`,
// `packages/*/src/**` and `services/*/src/**`.
const SOURCE_ROOTS: ReadonlyArray<RegExp> = [
  /^(?:src|app|lib|crates)\//,
  /^(?:packages|services)\/[^/]+\/src\//,
];

// The retired table's exclude list, kept as the allowed generated surface.
const GENERATED_OUTPUT = /^packages\/[^/]+\/src\/(?:.+\/)?generated\//;
const ALLOWED_GENERATED: ReadonlyArray<RegExp> = [
  GENERATED_OUTPUT,
  /^crates\/[^/]+\/bindings\//,
  /^crates\/longhorn-bindings\/src\//,
];
const GENERATOR_SOURCE = /^crates\/longhorn-bindings\/src\/.+\.rs$/;

// The scanner's rule tables, copied from effigy-scan's constants and heuristics.
const GENERATED_PATH_COMPONENTS: ReadonlySet<string> = new Set(["gen", "generated"]);
const GENERATED_NAME_MARKERS: ReadonlyArray<string> = [
  ".bundle.",
  ".chunk.",
  ".designer.",
  ".g.",
  ".generated.",
  ".min.",
  ".pb.",
  "_pb2.py",
];
const GENERATED_MARKERS: ReadonlyArray<string> = [
  "@generated",
  "auto-generated",
  "autogenerated",
  "code generated",
  "derived binding",
  "do not edit",
  "do not hand-edit",
  "do not modify",
  "generated by",
  "generated file",
  "machine generated",
  "not editable",
  "this file is generated",
];
const COMMENT_PREFIXES: ReadonlyArray<string> = ["//", "/*", "*", "<!--", "--", ";"];
const HEADER_LINES = 24;

// This check and its test name the header and markers as data, not as output.
const HEADER_DATA_EXCLUDES = [
  ":(exclude)scripts/check-generated-sources.ts",
  ":(exclude)scripts/check-generated-sources.test.ts",
];

export type GeneratedReason = "generated-path" | "generated-name" | "generated-marker";

const REASON_TEXT: Readonly<Record<GeneratedReason, string>> = {
  "generated-path": "generated path component in a source tree",
  "generated-name": "generated file name in a source tree",
  "generated-marker": "generated header marker in a source tree",
};

export type SourceFile = { readonly path: string; readonly text: string };

export type GeneratedSourceInputs = {
  // Tracked text files in a source root, plus any tracked file with the header.
  readonly files: ReadonlyArray<SourceFile>;
};

export function isSourceRootPath(path: string): boolean {
  return SOURCE_ROOTS.some((root) => root.test(path));
}

export function isAllowedGeneratedPath(path: string): boolean {
  return ALLOWED_GENERATED.some((allowed) => allowed.test(path));
}

// Blanks out string literals (single, double and backtick quotes, Rust-style
// raw strings) so that markers inside them do not count. Mirrors the scanner's
// mask, which replaces each literal character with a space.
export function maskStringLiterals(line: string): string {
  const chars = Array.from(line);
  const out: Array<string> = [];
  let index = 0;
  let quote: string | undefined;
  let rawHashes: number | undefined;
  let escaped = false;
  while (index < chars.length) {
    if (rawHashes !== undefined) {
      const closing = chars.slice(index + 1, index + 1 + rawHashes);
      if (
        chars[index] === '"' &&
        closing.length === rawHashes &&
        closing.every((char) => char === "#")
      ) {
        out.push(" ".repeat(1 + rawHashes));
        index += 1 + rawHashes;
        rawHashes = undefined;
        continue;
      }
      out.push(" ");
      index += 1;
      continue;
    }
    const ch = chars[index] ?? "";
    if (quote !== undefined) {
      if (escaped) {
        escaped = false;
      } else if (ch === "\\") {
        escaped = true;
      } else if (ch === quote) {
        quote = undefined;
      }
      out.push(" ");
      index += 1;
      continue;
    }
    const raw = rawStringPrefix(chars, index);
    if (raw !== undefined) {
      out.push(" ".repeat(raw.consumed));
      index += raw.consumed;
      rawHashes = raw.hashes;
      continue;
    }
    if (ch === "'" || ch === '"' || ch === "`") {
      quote = ch;
      out.push(" ");
    } else {
      out.push(ch);
    }
    index += 1;
  }
  return out.join("");
}

function rawStringPrefix(
  chars: ReadonlyArray<string>,
  index: number,
): { readonly consumed: number; readonly hashes: number } | undefined {
  let cursor = index;
  if (chars[cursor] === "b" && chars[cursor + 1] === "r") {
    cursor += 2;
  } else if (chars[cursor] === "r") {
    cursor += 1;
  } else {
    return undefined;
  }
  let hashes = 0;
  while (chars[cursor] === "#") {
    hashes += 1;
    cursor += 1;
  }
  if (chars[cursor] !== '"') {
    return undefined;
  }
  return { consumed: cursor - index + 1, hashes };
}

function isGeneratedHeaderLine(rawLine: string): boolean {
  const lower = maskStringLiterals(rawLine).toLowerCase();
  const trimmed = lower.trimStart();
  const commentLike =
    COMMENT_PREFIXES.some((prefix) => trimmed.startsWith(prefix)) ||
    (trimmed.startsWith("#") && !trimmed.startsWith("#["));
  return commentLike && GENERATED_MARKERS.some((marker) => lower.includes(marker));
}

// The scanner's three rules for one file. Empty when the file looks maintained.
export function generatedArtifactReasons(path: string, text: string): Array<GeneratedReason> {
  const reasons: Array<GeneratedReason> = [];
  const components = path.split("/");
  if (components.some((component) => GENERATED_PATH_COMPONENTS.has(component))) {
    reasons.push("generated-path");
  }
  const name = (components.at(-1) ?? "").toLowerCase();
  if (GENERATED_NAME_MARKERS.some((marker) => name.includes(marker))) {
    reasons.push("generated-name");
  }
  if (text.split(/\r?\n/).slice(0, HEADER_LINES).some(isGeneratedHeaderLine)) {
    reasons.push("generated-marker");
  }
  return reasons;
}

export function generatedSourceProblems(inputs: GeneratedSourceInputs): Array<string> {
  const problems: Array<string> = [];
  const generatorSource = inputs.files
    .filter((file) => GENERATOR_SOURCE.test(file.path))
    .map((file) => file.text)
    .join("\n");
  for (const file of inputs.files) {
    if (isAllowedGeneratedPath(file.path)) {
      // Allowed output is checked below; allowed generator sources need no rule.
    } else if (isSourceRootPath(file.path)) {
      for (const reason of generatedArtifactReasons(file.path, file.text)) {
        problems.push(`${file.path}: ${REASON_TEXT[reason]}`);
      }
    } else if (file.text.includes(GENERATOR_HEADER)) {
      problems.push(
        `${file.path}: generator header outside generated output and the bindings generator sources`,
      );
    }
    if (GENERATED_OUTPUT.test(file.path)) {
      if (!file.path.endsWith(".json") && !file.text.includes(GENERATOR_HEADER)) {
        problems.push(`${file.path}: file in a generated directory lacks the generator header`);
      }
      if (!generatorSource.includes(file.path)) {
        problems.push(
          `${file.path}: file in a generated directory is not named by a bindings generator`,
        );
      }
    }
  }
  return problems;
}

function git(args: ReadonlyArray<string>): string {
  const result = spawnSync("git", [...args], { cwd: repoRoot, encoding: "utf8" });
  // git grep exits 1 when nothing matches; other failures are errors.
  if (result.status === 1) {
    return "";
  }
  if (result.status !== 0) {
    throw new Error(`git ${args[0]} failed: ${result.stderr || String(result.error)}`);
  }
  return result.stdout;
}

export async function gatherGeneratedSourceInputs(): Promise<GeneratedSourceInputs> {
  const tracked = git(["ls-files"])
    .split("\n")
    .filter((path) => path !== "");
  const headerPaths = git([
    "grep",
    "-l",
    "-F",
    "-e",
    GENERATOR_HEADER,
    "--",
    ".",
    ...HEADER_DATA_EXCLUDES,
  ])
    .split("\n")
    .filter((path) => path !== "");
  const wanted = [...new Set([...tracked.filter(isSourceRootPath), ...headerPaths])];
  const files = await Promise.all(
    wanted.map(async (path) => ({
      path,
      text: await readFile(resolve(repoRoot, path), "utf8"),
    })),
  );
  return { files };
}

if (import.meta.main) {
  const problems = generatedSourceProblems(await gatherGeneratedSourceInputs());
  if (problems.length > 0) {
    for (const problem of problems) {
      console.error(`check:generated-sources: ${problem}`);
    }
    process.exit(1);
  }
  console.log("check:generated-sources: generated output and generator sources agree");
}
