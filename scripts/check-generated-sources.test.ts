import { describe, expect, test } from "bun:test";

import {
  GENERATOR_HEADER,
  gatherGeneratedSourceInputs,
  generatedInSrcFinding,
  generatedInSrcReason,
  generatedInSrcSeverity,
  generatedSourceProblems,
} from "./check-generated-sources.ts";
import type { SourceFile } from "./check-generated-sources.ts";

const generatedFile = "packages/longhorn/src/bridge/generated/fields.ts";
const generatorSource = `const OUT = "${generatedFile}";`;
const headerLine = `// ${GENERATOR_HEADER}bridge\`; do not edit.\n`;

// A source file as the gather step would hand it over: bytes and the sample.
function file(path: string, text: string): SourceFile {
  return { path, bytes: Buffer.byteLength(text), sample: text };
}

function problemsFor(files: ReadonlyArray<{ path: string; text: string }>): Array<string> {
  return generatedSourceProblems({
    files: files.map((f) => file(f.path, f.text)),
    generatorSource,
  });
}

describe("the repository", () => {
  test("the scanner's rules over the source roots, the generated output and the generator sources agree", async () => {
    expect(generatedSourceProblems(await gatherGeneratedSourceInputs())).toEqual([]);
  });
});

describe("rule 1: a generated header in the first 24 lines", () => {
  test("a header comment in a source tree is generated-marker", () => {
    expect(
      problemsFor([{ path: "crates/x/src/lib.rs", text: "// do not edit\nfn a() {}\n" }]),
    ).toEqual(["crates/x/src/lib.rs: generated-marker in a source tree"]);
  });

  test("each header phrase is a generated-marker", () => {
    for (const phrase of [
      "@generated",
      "auto-generated",
      "autogenerated",
      "code generated",
      "do not edit",
      "generated by",
    ]) {
      expect(generatedInSrcReason("crates/x/src/lib.rs", `// ${phrase}\n`)).toBe(
        "generated-marker",
      );
    }
  });

  test("a hash-comment header in a Python source tree is generated-marker", () => {
    expect(
      problemsFor([{ path: "packages/x/src/tool.py", text: "# generated by tool\n" }]),
    ).toEqual(["packages/x/src/tool.py: generated-marker in a source tree"]);
  });

  test("a phrase in a string literal or in prose is not a header", () => {
    expect(generatedInSrcReason("crates/x/src/lib.rs", 'let s = "do not edit";\n')).toBeUndefined();
    expect(
      generatedInSrcReason("crates/x/src/lib.rs", "This file is generated by hand.\n"),
    ).toBeUndefined();
  });

  test("a header beyond the first 24 lines is not read", () => {
    expect(
      generatedInSrcReason("crates/x/src/lib.rs", `${"\n".repeat(24)}// do not edit\n`),
    ).toBeUndefined();
  });
});

describe("rule 2: a source map", () => {
  test("app.js.map is source-map", () => {
    expect(generatedInSrcReason("src/app.js.map", '{"version":3}\n')).toBe("source-map");
  });

  test("the suffix matches in any source root, case-insensitively", () => {
    expect(generatedInSrcReason("app/app.js.map", "x\n")).toBe("source-map");
    expect(generatedInSrcReason("crates/c/src/X.JS.MAP", "x\n")).toBe("source-map");
    expect(generatedInSrcReason("packages/p/src/y.js.map", "x\n")).toBe("source-map");
    expect(generatedInSrcReason("services/s/src/q.map", "x\n")).toBe("source-map");
    expect(generatedInSrcReason("src/.map", "x\n")).toBe("source-map");
  });

  test("a sourcemap name without the dot is not a source map", () => {
    expect(generatedInSrcReason("src/plain.sourcemap", "x\n")).toBeUndefined();
  });

  test("a map name with a suffix after .map is a filename-marker, as the scanner matched it", () => {
    expect(generatedInSrcReason("src/app.js.map.bak", "x\n")).toBe("filename-marker");
    expect(generatedInSrcReason("src/a.mapper.ts", "x\n")).toBe("filename-marker");
  });

  test("a source map outside the source roots is not flagged", () => {
    expect(
      problemsFor([
        { path: "docs/z.map", text: "x\n" },
        { path: "examples/app.js.map", text: "x\n" },
      ]),
    ).toEqual([]);
  });
});

describe("rule 3: a minified asset", () => {
  test(".min. in the name is minified-asset", () => {
    expect(generatedInSrcReason("src/x.min.css", "x\n")).toBe("minified-asset");
    expect(generatedInSrcReason("src/v.MIN.JS", "x\n")).toBe("minified-asset");
  });

  test("a name ending in .min without a trailing dot is not", () => {
    expect(generatedInSrcReason("src/x.min", "x\n")).toBeUndefined();
  });
});

describe("rule 4: a generated file name", () => {
  test("each name marker is a filename-marker", () => {
    for (const name of [
      "w.bundle.py",
      "c.chunk.js",
      "y.generated.json",
      "y.generated.rs",
      "d.pb.ts",
      "d.designer.cs",
      "d.g.ts",
    ]) {
      expect(generatedInSrcReason(`src/${name}`, "x\n")).toBe("filename-marker");
    }
  });

  test("the scanner did not match _pb2.py", () => {
    expect(generatedInSrcReason("src/q_pb2.py", "x\n")).toBeUndefined();
  });
});

describe("rule 5: a generated path component", () => {
  test("a gen or generated directory is generated-path-component", () => {
    expect(problemsFor([{ path: "crates/x/src/gen/mod.rs", text: "pub fn a() {}\n" }])).toEqual([
      "crates/x/src/gen/mod.rs: generated-path-component in a source tree",
    ]);
    expect(generatedInSrcReason("src/generated/y.ts", "x\n")).toBe("generated-path-component");
  });

  test("a file named gen is not a directory", () => {
    expect(generatedInSrcReason("src/gen.ts", "x\n")).toBeUndefined();
  });
});

describe("precedence", () => {
  test("a header wins over a name rule", () => {
    expect(generatedInSrcReason("src/app.js.map", "// do not edit\n")).toBe("generated-marker");
    expect(generatedInSrcReason("src/x.min.js", "// do not edit\n")).toBe("generated-marker");
  });

  test("a name rule wins over a path component", () => {
    expect(generatedInSrcReason("src/gen/a.map", "x\n")).toBe("source-map");
  });
});

describe("source roots", () => {
  test("only the scanner's roots are checked", () => {
    expect(
      problemsFor([
        { path: "scripts/gen/x.ts", text: "// do not edit\n" },
        { path: "prototypes/x/src/a.map", text: "x\n" },
      ]),
    ).toEqual([]);
    expect(problemsFor([{ path: "services/s/src/q.map", text: "x\n" }])).toEqual([
      "services/s/src/q.map: source-map in a source tree",
    ]);
  });
});

describe("severity classes by size", () => {
  test("zero bytes is nothing, and the classes start at the scanner's thresholds", () => {
    expect(generatedInSrcSeverity(0)).toBeUndefined();
    expect(generatedInSrcSeverity(1)).toBe("warning");
    expect(generatedInSrcSeverity(19_999)).toBe("warning");
    expect(generatedInSrcSeverity(20_000)).toBe("high");
    expect(generatedInSrcSeverity(199_999)).toBe("high");
    expect(generatedInSrcSeverity(200_000)).toBe("critical");
  });

  test("a zero-byte generated file is not a finding", () => {
    expect(generatedInSrcFinding({ path: "src/app.js.map", bytes: 0, sample: "" })).toBeUndefined();
  });
});

describe("generated output", () => {
  test("a generated file with its header and a generator path is accepted", () => {
    expect(problemsFor([{ path: generatedFile, text: `${headerLine}export {};\n` }])).toEqual([]);
  });

  test("a generated text file that lost its header is reported", () => {
    expect(problemsFor([{ path: generatedFile, text: "export {};\n" }])).toEqual([
      `${generatedFile}: file in a generated directory lacks the generator header`,
    ]);
  });

  test("a hand-written file in a generated directory is reported as not generator output", () => {
    const handWritten = "packages/longhorn/src/bridge/generated/notes.ts";
    expect(problemsFor([{ path: handWritten, text: "export {};\n" }])).toEqual([
      `${handWritten}: file in a generated directory lacks the generator header`,
      `${handWritten}: file in a generated directory is not named by a bindings generator`,
    ]);
  });

  test("JSON generator output needs no comment header, only a generator path", () => {
    const json = "packages/longhorn/src/licence/generated/key-conformance.json";
    expect(
      generatedSourceProblems({
        files: [file(json, "{}\n")],
        generatorSource: `const K = "${json}";`,
      }),
    ).toEqual([]);
  });

  test("the generator sources may carry the header they write", () => {
    expect(
      problemsFor([{ path: "crates/longhorn-bindings/src/bridge.rs", text: headerLine }]),
    ).toEqual([]);
  });

  test("the allowed surface is skipped by the scanner rules", () => {
    expect(problemsFor([{ path: generatedFile, text: `${headerLine}// do not edit\n` }])).toEqual(
      [],
    );
  });
});

describe("the generator header outside the source roots", () => {
  test("a docs file carrying the generator header is reported", () => {
    expect(problemsFor([{ path: "docs/notes.md", text: headerLine }])).toEqual([
      "docs/notes.md: generator header outside generated output and the bindings generator sources",
    ]);
  });

  test("the header in a source tree outside the allowed surface is a generated-marker", () => {
    expect(problemsFor([{ path: "packages/x/src/hand.ts", text: headerLine }])).toEqual([
      "packages/x/src/hand.ts: generated-marker in a source tree",
    ]);
  });
});
