import { describe, expect, test } from "bun:test";

import {
  GENERATOR_HEADER,
  gatherGeneratedSourceInputs,
  generatedSourceProblems,
} from "./check-generated-sources.ts";

const generatedFile = "packages/longhorn/src/bridge/generated/fields.ts";
const generatorSource = `const OUT = "${generatedFile}";`;

describe("generatedSourceProblems", () => {
  test("the repository's generated output and generator sources agree", async () => {
    expect(generatedSourceProblems(await gatherGeneratedSourceInputs())).toEqual([]);
  });

  test("a generator header outside generated output is reported", () => {
    const problems = generatedSourceProblems({
      headerPaths: ["packages/longhorn/src/bridge/hand-written.ts", generatedFile],
      generatedFiles: [{ path: generatedFile, hasHeader: true }],
      generatorSource,
    });
    expect(problems).toEqual([
      "packages/longhorn/src/bridge/hand-written.ts: generator header outside generated output and the bindings generator sources",
    ]);
  });

  test("a generated file that lost its generator header is reported", () => {
    const problems = generatedSourceProblems({
      headerPaths: [],
      generatedFiles: [{ path: generatedFile, hasHeader: false }],
      generatorSource,
    });
    expect(problems).toEqual([
      `${generatedFile}: file in a generated directory lacks the generator header`,
    ]);
  });

  test("a hand-written file in a generated directory is reported as not generator output", () => {
    const handWritten = "packages/longhorn/src/bridge/generated/notes.ts";
    const problems = generatedSourceProblems({
      headerPaths: [],
      generatedFiles: [{ path: handWritten, hasHeader: false }],
      generatorSource,
    });
    expect(problems).toEqual([
      `${handWritten}: file in a generated directory lacks the generator header`,
      `${handWritten}: file in a generated directory is not named by a bindings generator`,
    ]);
  });

  test("JSON generator output needs no comment header, only a generator path", () => {
    const json = "packages/longhorn/src/licence/generated/key-conformance.json";
    expect(
      generatedSourceProblems({
        headerPaths: [],
        generatedFiles: [{ path: json, hasHeader: false }],
        generatorSource: `const K = "${json}";`,
      }),
    ).toEqual([]);
  });

  test("the bindings generator sources may carry the header they write", () => {
    expect(
      generatedSourceProblems({
        headerPaths: ["crates/longhorn-bindings/src/bridge.rs"],
        generatedFiles: [{ path: generatedFile, hasHeader: true }],
        generatorSource,
      }),
    ).toEqual([]);
  });

  test("the header constant is the generators' own marker", () => {
    expect(GENERATOR_HEADER).toBe("@generated by `effigy ");
  });
});
