import { describe, expect, test } from "bun:test";

import {
  GENERATOR_HEADER,
  gatherGeneratedSourceInputs,
  generatedArtifactReasons,
  generatedSourceProblems,
  maskStringLiterals,
} from "./check-generated-sources.ts";

const generatedFile = "packages/longhorn/src/bridge/generated/fields.ts";
const generatorSource = {
  path: "crates/longhorn-bindings/src/bridge.rs",
  text: `const OUT = "${generatedFile}";`,
};
const headerLine = `// ${GENERATOR_HEADER}bridge\`; do not edit.\n`;

function problemsFor(files: ReadonlyArray<{ path: string; text: string }>): Array<string> {
  return generatedSourceProblems({ files: [generatorSource, ...files] });
}

describe("the repository", () => {
  test("the scanner's source roots, generated output and generator sources agree", async () => {
    expect(generatedSourceProblems(await gatherGeneratedSourceInputs())).toEqual([]);
  });
});

describe("the scanner's three generated-file rules", () => {
  test("a path component named gen or generated in a source tree is reported", () => {
    expect(problemsFor([{ path: "crates/x/src/gen/mod.rs", text: "pub fn a() {}\n" }])).toEqual([
      "crates/x/src/gen/mod.rs: generated path component in a source tree",
    ]);
  });

  test("a generated-name marker in a source tree is reported", () => {
    expect(
      problemsFor([
        { path: "packages/x/src/widget.generated.ts", text: "export {};\n" },
        { path: "crates/x/src/app.min.js", text: "x\n" },
        { path: "crates/x/src/proto_pb2.py", text: "x\n" },
      ]),
    ).toEqual([
      "packages/x/src/widget.generated.ts: generated file name in a source tree",
      "crates/x/src/app.min.js: generated file name in a source tree",
      "crates/x/src/proto_pb2.py: generated file name in a source tree",
    ]);
  });

  test("a generated header marker in a comment-like line of a source tree is reported", () => {
    expect(
      problemsFor([
        { path: "crates/x/src/lib.rs", text: "// Do not edit: produced by a tool.\nfn a() {}\n" },
      ]),
    ).toEqual(["crates/x/src/lib.rs: generated header marker in a source tree"]);
  });

  test("a hash-comment header in a source tree is reported", () => {
    expect(
      problemsFor([{ path: "packages/x/src/tool.py", text: "# generated by tool\n" }]),
    ).toEqual(["packages/x/src/tool.py: generated header marker in a source tree"]);
  });

  test("the same markers outside the source roots are not this rule's concern", () => {
    expect(
      problemsFor([
        { path: "scripts/gen/x.ts", text: "// do not edit\n" },
        { path: "examples/app/widget.generated.ts", text: "export {};\n" },
      ]),
    ).toEqual([]);
  });

  test("a marker beyond the first 24 lines is not reported", () => {
    expect(
      problemsFor([{ path: "crates/x/src/lib.rs", text: `${"\n".repeat(24)}// do not edit\n` }]),
    ).toEqual([]);
  });

  test("a marker in prose rather than a comment-like line is not reported", () => {
    expect(
      problemsFor([{ path: "crates/x/src/lib.rs", text: "This file is generated by hand.\n" }]),
    ).toEqual([]);
  });

  test("a marker inside a string literal is masked and not reported", () => {
    expect(
      problemsFor([{ path: "crates/x/src/lib.rs", text: 'let s = "do not edit";\n' }]),
    ).toEqual([]);
    expect(
      problemsFor([{ path: "crates/x/src/lib.rs", text: 'let s = r#"do not edit"#;\n' }]),
    ).toEqual([]);
  });
});

describe("generatedArtifactReasons", () => {
  test("reports each rule that matches, in the scanner's order", () => {
    expect(generatedArtifactReasons("crates/x/src/gen/a.generated.rs", "// do not edit\n")).toEqual(
      ["generated-path", "generated-name", "generated-marker"],
    );
  });

  test("a maintained file reports nothing", () => {
    expect(generatedArtifactReasons("crates/x/src/lib.rs", "pub fn a() {}\n")).toEqual([]);
  });
});

describe("maskStringLiterals", () => {
  test("blanks single, double and backtick literals, keeping comments", () => {
    const masked = maskStringLiterals('a("do not edit") // generated by x');
    expect(masked).not.toContain("do not edit");
    expect(masked).toContain("// generated by x");
  });

  test("an escaped quote does not close the literal", () => {
    expect(maskStringLiterals(String.raw`"a\" do not edit" // keep`)).not.toContain("do not edit");
  });
});

describe("generated output", () => {
  test("a generated file with its header and a generator path is accepted", () => {
    expect(problemsFor([{ path: generatedFile, text: `${headerLine}export {};\n` }])).toEqual([]);
  });

  test("a generated text file that lost its header is reported", () => {
    expect(problemsFor([{ path: generatedFile, text: "export {};\n" }])).toEqual([
      `${generatedFile}: file in a generated directory lacks the generator header`,
    ]);
  });

  test("a hand-written file in a generated directory is reported as not generator output", () => {
    const handWritten = "packages/longhorn/src/bridge/generated/notes.ts";
    expect(problemsFor([{ path: handWritten, text: "export {};\n" }])).toEqual([
      `${handWritten}: file in a generated directory lacks the generator header`,
      `${handWritten}: file in a generated directory is not named by a bindings generator`,
    ]);
  });

  test("JSON generator output needs no comment header, only a generator path", () => {
    const json = "packages/longhorn/src/licence/generated/key-conformance.json";
    expect(
      generatedSourceProblems({
        files: [
          { path: "crates/longhorn-bindings/src/licence.rs", text: `const K = "${json}";` },
          { path: json, text: "{}\n" },
        ],
      }),
    ).toEqual([]);
  });

  test("the generator sources may carry the header they write", () => {
    expect(
      problemsFor([{ path: "crates/longhorn-bindings/src/bridge.rs", text: headerLine }]),
    ).toEqual([]);
  });
});

describe("the generator header outside the source roots", () => {
  test("a docs file carrying the generator header is reported", () => {
    expect(problemsFor([{ path: "docs/notes.md", text: headerLine }])).toEqual([
      "docs/notes.md: generator header outside generated output and the bindings generator sources",
    ]);
  });

  test("the header in a source tree outside the allowed surface is reported as a marker", () => {
    expect(problemsFor([{ path: "packages/x/src/hand.ts", text: headerLine }])).toEqual([
      "packages/x/src/hand.ts: generated header marker in a source tree",
    ]);
  });
});
