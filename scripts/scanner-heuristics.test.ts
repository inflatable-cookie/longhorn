import { describe, expect, test } from "bun:test";

import {
  GENERATED_HEADER_PHRASES,
  hasGeneratedHeader,
  isGeneratedHeaderLine,
  maskStringLiterals,
} from "./scanner-heuristics.ts";

describe("maskStringLiterals", () => {
  test("blanks double, single and backtick literals and keeps the code around them", () => {
    const masked = maskStringLiterals('a("do not edit") // generated by x');
    expect(masked).not.toContain("do not edit");
    expect(masked).toContain("// generated by x");
  });

  test("a backtick literal is masked as well", () => {
    expect(maskStringLiterals("let s = `do not edit`; // keep")).not.toContain("do not edit");
  });

  test("an escaped quote does not end the literal", () => {
    expect(maskStringLiterals(String.raw`"a\" do not edit" // keep`)).not.toContain("do not edit");
  });

  test("a raw string with hashes is masked up to its closing hash", () => {
    expect(maskStringLiterals('let s = r#"do not edit"#; // keep')).not.toContain("do not edit");
  });
});

describe("header phrases", () => {
  test("exactly the six phrases the scanner matched", () => {
    expect([...GENERATED_HEADER_PHRASES]).toEqual([
      "@generated",
      "auto-generated",
      "autogenerated",
      "code generated",
      "do not edit",
      "generated by",
    ]);
  });

  test("each phrase on a comment-like line is a generated header", () => {
    for (const phrase of GENERATED_HEADER_PHRASES) {
      expect(isGeneratedHeaderLine(`// ${phrase}`)).toBe(true);
    }
  });

  test("phrases the scanner did not match are not headers", () => {
    for (const phrase of [
      "derived binding",
      "do not hand-edit",
      "do not modify",
      "generated file",
      "machine generated",
      "not editable",
      "this file is generated",
    ]) {
      expect(isGeneratedHeaderLine(`// ${phrase}`)).toBe(false);
    }
  });

  test("the comment prefixes the scanner accepted, and a hash comment outside #[", () => {
    for (const line of [
      "// do not edit",
      "/* do not edit",
      " * do not edit",
      "<!-- do not edit",
      "-- do not edit",
      "; do not edit",
      "# do not edit",
    ]) {
      expect(isGeneratedHeaderLine(line)).toBe(true);
    }
    expect(isGeneratedHeaderLine("#[do_not_edit]")).toBe(false);
  });

  test("a phrase in prose, with no comment prefix, is not a header", () => {
    expect(isGeneratedHeaderLine("This file is generated by hand.")).toBe(false);
  });

  test("a phrase inside a string literal is masked, so the line is not a header", () => {
    expect(isGeneratedHeaderLine('let s = "do not edit";')).toBe(false);
  });

  test("only the first 24 lines are read", () => {
    expect(hasGeneratedHeader(`${"\n".repeat(23)}// do not edit`)).toBe(true);
    expect(hasGeneratedHeader(`${"\n".repeat(24)}// do not edit`)).toBe(false);
  });
});
