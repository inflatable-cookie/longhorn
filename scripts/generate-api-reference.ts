import { readCargoInventory } from "./cargo-metadata.ts";
import {
  readPackageManifest,
  requireList,
  requireRecord,
  requireString,
  requireStrings,
} from "./proof-json.ts";
import { run, sha256 } from "./proof-support.ts";
import { access, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve, sep } from "node:path";

import { parseWorkspacePackageVersion } from "./longhorn-version.ts";
import { rustCommand } from "./rust-command.ts";

const repoRoot = resolve(import.meta.dir, "..");
const outputPath = join(repoRoot, "docs/reference/api-surface.md");
const write = process.argv.includes("--write");

// The version is read from the workspace, not written here — a bump must not
// fail this gate as "identity drift".
const workspaceManifest = await readFile(join(repoRoot, "Cargo.toml"), "utf8");
const workspaceVersion = parseWorkspacePackageVersion(workspaceManifest);

const content = await renderReference();
if (write) {
  await writeFile(outputPath, content);
} else {
  const current = await readFile(outputPath, "utf8");
  if (current !== content) {
    throw new Error("API surface reference is stale; run `effigy generate:api-reference`");
  }
}

console.log(
  JSON.stringify(
    {
      schema: "longhorn.api-reference-generation.v1",
      mode: write ? "write" : "check",
      output: relative(repoRoot, outputPath),
      sha256: sha256(content),
    },
    null,
    2,
  ),
);

async function renderReference(): Promise<string> {
  const cargo = readCargoInventory(
    await run(
      rustCommand(["metadata", "--locked", "--no-deps", "--format-version", "1"]),
      repoRoot,
    ),
  );
  const crateRoot = join(repoRoot, "crates") + sep;
  const rustPackages = cargo.packages
    .filter(
      ({ manifest_path, name }) =>
        manifest_path.startsWith(crateRoot) && name.startsWith("longhorn-"),
    )
    .sort((left, right) => left.name.localeCompare(right.name));
  const crateDirectories = (
    await readdir(join(repoRoot, "crates"), { withFileTypes: true })
  ).filter((entry) => entry.isDirectory());
  if (rustPackages.length !== crateDirectories.length) {
    throw new Error(
      `Rust inventory mismatch: metadata ${rustPackages.length}, directories ${crateDirectories.length}`,
    );
  }

  const packageDirectories = (await readdir(join(repoRoot, "packages"), { withFileTypes: true }))
    .filter((entry) => entry.isDirectory())
    .sort((left, right) => left.name.localeCompare(right.name));
  const typescriptPackages = [];
  for (const directory of packageDirectories) {
    const manifestPath = join(repoRoot, "packages", directory.name, "package.json");
    if (!(await exists(manifestPath))) {
      continue;
    }
    const manifest = readPackageManifest(await readFile(manifestPath, "utf8"));
    if (
      (manifest.name !== "@inflatable-cookie/longhorn" &&
        !manifest.name.startsWith("@inflatable-cookie/longhorn-")) ||
      manifest.version !== workspaceVersion
    ) {
      throw new Error(`${directory.name} package identity drift`);
    }
    // These carried `private: true` until Card 166 made them publishable. The
    // posture to hold is now the publishable one: a scoped package needs
    // `publishConfig.access` to go out publicly, and a tarball without a
    // licence is worse than one that never ships.
    const posture = requireRecord(manifest, "package manifest");
    if (
      posture.private === true ||
      requireRecord(posture.publishConfig, "publish config").access !== "public" ||
      posture.license !== "MIT" ||
      requireRecord(posture.repository, "repository").directory !== `packages/${directory.name}`
    ) {
      throw new Error(`${directory.name} publish posture drift`);
    }
    const entrypoints = [];
    for (const [subpath, target] of Object.entries(
      requireRecord(manifest.exports, "package exports"),
    )) {
      if (subpath === "./package.json") {
        continue;
      }
      const conditions = typeof target === "string" ? {} : requireRecord(target, subpath);
      const source =
        typeof target === "string"
          ? target
          : (conditions.types ?? conditions.svelte ?? conditions.import ?? conditions.default);
      if (typeof source !== "string" || !source.startsWith("./src/") || source.includes("../")) {
        throw new Error(`${manifest.name} export ${subpath} escapes public source roots`);
      }
      await access(join(dirname(manifestPath), source));
      entrypoints.push(subpath === "." ? manifest.name : `${manifest.name}/${subpath.slice(2)}`);
    }
    typescriptPackages.push({
      directory: directory.name,
      manifest,
      entrypoints: entrypoints.sort(),
    });
  }

  const lines = [
    "# Generated API Surface",
    "",
    "> Generated by `scripts/generate-api-reference.ts`. Do not edit by hand.",
    `> The three TypeScript packages are prepared for npm publication at \`${workspaceVersion}\` under MIT; the Rust crates set \`publish = false\` and are not on crates.io.`,
    "",
    "## Rust Crates",
    "",
    "`cargo doc` is the symbol-level reference. This table is the checked package and feature front door.",
    "",
    "| Crate | Kind | Features | Source reference |",
    "| --- | --- | --- | --- |",
  ];

  for (const pkg of rustPackages) {
    const metadata = requireRecord(pkg, "Cargo package");
    if (
      pkg.version !== workspaceVersion ||
      !Array.isArray(metadata.publish) ||
      metadata.publish.length !== 0
    ) {
      throw new Error(`${pkg.name} version or private publication posture drift`);
    }
    const directory = dirname(pkg.manifest_path);
    const relativeDirectory = relative(repoRoot, directory).split(sep).join("/");
    const readme = join(directory, "README.md");
    const library = requireList(metadata.targets, "Cargo targets")
      .map((target) => requireRecord(target, "Cargo target"))
      .find(({ kind }) => requireStrings(kind, "target kind").includes("lib"));
    const reference = (await exists(readme))
      ? `../../${relativeDirectory}/README.md`
      : library
        ? `../../${relative(repoRoot, requireString(library.src_path, "lib source path")).split(sep).join("/")}`
        : `../../${relativeDirectory}/Cargo.toml`;
    const kind = library ? "library" : "development tool";
    const features = formatFeatures(
      Object.fromEntries(
        Object.entries(requireRecord(metadata.features, "crate features")).map(
          ([name, entries]) => [name, requireStrings(entries, name)],
        ),
      ),
    );
    lines.push(`| \`${pkg.name}\` | ${kind} | ${features} | [source](${reference}) |`);
  }

  lines.push(
    "",
    "All crates currently set `publish = false`. `longhorn-bindings` is a development tool, not a consumer dependency.",
    "",
    "## TypeScript And Svelte Packages",
    "",
    "Entrypoints come only from each package's checked `exports` map. A subpath is optional only when its peer is selected explicitly.",
    "",
    "| Package | Public entrypoints | Longhorn dependencies | Peer ranges | Reference |",
    "| --- | --- | --- | --- | --- |",
  );

  for (const { directory, manifest, entrypoints } of typescriptPackages) {
    const dependencies = Object.entries(manifest.dependencies ?? {})
      .filter(
        ([name]) =>
          name === "@inflatable-cookie/longhorn" || name.startsWith("@inflatable-cookie/longhorn-"),
      )
      .map(([name, version]) => `\`${name} ${version}\``);
    const peers = Object.entries(manifest.peerDependencies ?? {}).map(([name, version]) => {
      const optional = manifest.peerDependenciesMeta?.[name]?.optional === true ? "; optional" : "";
      return `\`${name} ${version}${optional}\``;
    });
    lines.push(
      `| \`${manifest.name}\` | ${entrypoints.map((entry) => `\`${entry}\``).join("<br>")} | ${dependencies.join("<br>") || "none"} | ${peers.join("<br>") || "none"} | [README](../../packages/${directory}/README.md) |`,
    );
  }

  lines.push(
    "",
    "Each package carries `publishConfig.access: public`, an MIT licence, and a repository directory, so `npm publish` is possible. Publication itself is Card 166's, and a guide may only imply registry installation once that has happened.",
  );
  return `${lines.join("\n")}\n`;
}

function formatFeatures(features: Record<string, Array<string>>): string {
  const names = Object.keys(features).sort();
  if (names.length === 0) {
    return "none";
  }
  return names.map((name) => `\`${name}\``).join(", ");
}

async function exists(path: string): Promise<boolean> {
  try {
    await access(path);
    return true;
  } catch {
    return false;
  }
}
